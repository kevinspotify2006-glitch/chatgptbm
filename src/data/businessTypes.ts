const byId = new Map(BUSINESS_TYPES.map((type) => [type.id, type]));

export function businessType(id: string): BusinessTypeDef | undefined {
  return byId.get(id);
}

export function businessTypeOrThrow(id: string): BusinessTypeDef {
  const found = byId.get(id);
  if (!found) throw new Error(`Unknown business type: ${id}`);
  return found;
}

export const CATEGORY_NAMES: Record<BusinessCategory, string> = {
  retail: 'Retail',
  food: 'Food',
  services: 'Services',
  specialized: 'Specialized',
};

export function typesForCategory(category: BusinessCategory): BusinessTypeDef[] {
  return BUSINESS_TYPES.filter((type) => type.category === category);
}
